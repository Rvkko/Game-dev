/**
 * Turn a layout definition into flat typed arrays.
 * Returns { name, walls: Uint8Array, portal: Int32Array, portalCells: number[] }
 * where portal[cell] is the destination cell index, or -1.
 */
export function parseLayout(layout) {
  const walls = new Uint8Array(CELLS);
  const portal = new Int32Array(CELLS).fill(-1);
  const pads = new Map(); // digit -> [cellA, cellB]
  const portalCells = [];
  for (let r = 0; r < ROWS; r++) {
    const raw = layout.rows[r] || '';
    const line = raw.length >= COLS ? raw : raw.padEnd(COLS, '.');
    for (let c = 0; c < COLS; c++) {
      const ch = line[c];
      const idx = r * COLS + c;
      if (ch === '#') walls[idx] = 1;
      else if (ch >= '1' && ch <= '9') {
        if (!pads.has(ch)) pads.set(ch, []);
        pads.get(ch).push(idx);
        portalCells.push(idx);
      }
    }
  }
  for (const list of pads.values()) {
    if (list.length === 2) {
      portal[list[0]] = list[1];
      portal[list[1]] = list[0];
    }
  }
  return { name: layout.name, walls, portal, portalCells };
}

export function layoutsForMode(mode) {
  if (mode === 'maze') return MAZE_LAYOUTS;
  if (mode === 'portal') return PORTAL_LAYOUTS;
  return [EMPTY_LAYOUT];
}
